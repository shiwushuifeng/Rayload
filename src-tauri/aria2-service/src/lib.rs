//! Tauri-free Aria2 engine lifecycle for headless entry points.
//!
//! The service owns runtime-config generation, process spawning and the
//! parent-death binding. It deliberately has no Tauri or GUI dependency so the
//! CLI and future headless frontends can drive the same engine.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::{self, BufRead, BufReader};
use std::net::{SocketAddr, TcpStream};
use std::path::{Path, PathBuf};
use std::process::{Child, Command, ExitStatus, Stdio};
use std::sync::mpsc::{self, Receiver};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

pub const DEFAULT_RPC_PORT: u16 = 6800;
const BUNDLED_CONFIG: &str = include_str!("../../binaries/aria2.conf");
const READY_TIMEOUT: Duration = Duration::from_secs(15);

#[derive(Debug, Clone)]
pub struct Aria2Config {
    pub binary: PathBuf,
    pub data_dir: PathBuf,
    pub download_dir: PathBuf,
    pub rpc_port: u16,
    pub extra_options: BTreeMap<String, String>,
}

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("aria2 RPC port {0} is already in use")]
    PortInUse(u16),
    #[error("aria2 exited before opening its RPC port: {0}")]
    ExitedEarly(ExitStatus),
    #[error("aria2 did not open RPC port {0} within {1:?}")]
    NotReady(u16, Duration),
    #[error("path for aria2 option '{0}' is not valid UTF-8 or contains a line break")]
    InvalidPath(&'static str),
    #[error("aria2 option '{0}' has an invalid name or value")]
    InvalidOption(String),
    #[error(transparent)]
    Io(#[from] io::Error),
}

pub struct Aria2Service {
    config: Aria2Config,
}

impl Aria2Service {
    pub fn new(config: Aria2Config) -> Self {
        Self { config }
    }

    /// Writes the runtime config and starts the engine in the background.
    pub fn start(&self) -> Result<Aria2Process, Error> {
        std::net::TcpListener::bind(("127.0.0.1", self.config.rpc_port)).map_err(|error| {
            if error.kind() == io::ErrorKind::AddrInUse {
                Error::PortInUse(self.config.rpc_port)
            } else {
                Error::Io(error)
            }
        })?;

        std::fs::create_dir_all(&self.config.download_dir)?;
        let state_dir = self.config.data_dir.join("state");
        std::fs::create_dir_all(&state_dir)?;
        let session_path = self.config.data_dir.join("download.session");
        ensure_file(&session_path)?;

        let config_path = self.config.data_dir.join("aria2.conf");
        let content = self.render_config(&session_path, &state_dir)?;
        std::fs::write(&config_path, content)?;

        let args = [format!("--conf-path={}", config_path.display())];
        let child = spawn_child(&self.config.binary, &args, &[], true)?;

        Ok(Aria2Process {
            child,
            rpc_port: self.config.rpc_port,
        })
    }

    fn render_config(&self, session_path: &Path, state_dir: &Path) -> Result<String, Error> {
        let mut options = parse_bundled_config();
        for (key, value) in &self.config.extra_options {
            validate_option(key, value)?;
            options.insert(key.clone(), value.clone());
        }
        let mut set = |key: &str, value: String| {
            options.insert(key.to_string(), value);
        };

        set("dir", path_value(&self.config.download_dir, "dir")?);
        set("enable-rpc", "true".into());
        set("rpc-listen-port", self.config.rpc_port.to_string());
        // shortcut: RPC is unauthenticated on loopback; add rpc-secret before exposing it.
        set("rpc-listen-all", "false".into());
        set("rpc-allow-origin-all", "true".into());
        set("rpc-max-request-size", "16M".into());
        set("save-session", path_value(session_path, "save-session")?);
        set("save-session-interval", "60".into());
        set("input-file", path_value(session_path, "input-file")?);
        set("state-dir", path_value(state_dir, "state-dir")?);
        set("stop-with-process", std::process::id().to_string());
        set("quiet", "true".into());

        let mut output = String::from("# Generated by Rayload. Do not edit.\n");
        for (key, value) in options {
            writeln!(output, "{key}={value}")
                .map_err(|_| Error::Io(io::Error::other("failed to render aria2 config")))?;
        }
        Ok(output)
    }
}

pub struct Aria2Process {
    child: Child,
    rpc_port: u16,
}

impl Aria2Process {
    pub fn pid(&self) -> u32 {
        self.child.id()
    }

    /// Waits until the RPC port accepts connections.
    pub fn wait_until_ready(&mut self) -> Result<(), Error> {
        let deadline = Instant::now() + READY_TIMEOUT;
        let address = SocketAddr::from(([127, 0, 0, 1], self.rpc_port));
        loop {
            if TcpStream::connect_timeout(&address, Duration::from_millis(200)).is_ok() {
                return Ok(());
            }
            if let Some(status) = self.child.try_wait()? {
                return Err(Error::ExitedEarly(status));
            }
            if Instant::now() >= deadline {
                return Err(Error::NotReady(self.rpc_port, READY_TIMEOUT));
            }
            std::thread::sleep(Duration::from_millis(100));
        }
    }

    pub fn wait(&mut self) -> io::Result<ExitStatus> {
        self.child.wait()
    }

    pub fn stop(&mut self) -> io::Result<()> {
        if self.child.try_wait()?.is_some() {
            return Ok(());
        }
        #[cfg(unix)]
        // SAFETY: the child has not been reaped, so the PID still belongs to it.
        unsafe {
            libc::kill(self.child.id() as libc::pid_t, libc::SIGTERM);
        }
        #[cfg(not(unix))]
        self.child.kill()?;
        self.child.wait()?;
        Ok(())
    }
}

impl Drop for Aria2Process {
    fn drop(&mut self) {
        if self.child.try_wait().ok().flatten().is_none() {
            let _ = self.stop();
        }
    }
}

/// A lifecycle event from a supervised engine process.
#[derive(Debug)]
pub enum EngineEvent {
    Stdout(Vec<u8>),
    Stderr(Vec<u8>),
    Exited {
        code: Option<i32>,
        signal: Option<i32>,
    },
}

/// A running engine that can be terminated without owning its `Child`.
///
/// The waiter thread needs `&mut Child` to reap the process, so the handle is
/// shared behind a mutex. The lock is only taken for the short `try_wait`
/// poll or a kill, never while blocking.
pub struct EngineProcess {
    pid: u32,
    child: Arc<Mutex<Child>>,
}

impl EngineProcess {
    pub fn pid(&self) -> u32 {
        self.pid
    }

    /// Sends SIGKILL on Unix and terminates the process on Windows.
    pub fn kill(&self) -> io::Result<()> {
        let mut child = self
            .child
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        child.kill()
    }
}

/// A spawned engine plus its stdout/stderr/exit event stream.
pub struct SpawnedEngine {
    process: EngineProcess,
    events: Receiver<EngineEvent>,
}

impl SpawnedEngine {
    pub fn pid(&self) -> u32 {
        self.process.pid()
    }

    pub fn kill(&self) -> io::Result<()> {
        self.process.kill()
    }

    /// Splits the ownership handle from the event stream so the caller can
    /// store the handle and consume events separately.
    pub fn into_parts(self) -> (EngineProcess, Receiver<EngineEvent>) {
        (self.process, self.events)
    }
}

/// Spawns an engine with piped stdio and parent-death binding.
///
/// Events are delivered on a channel: stdout and stderr lines as they arrive,
/// then [`EngineEvent::Exited`] once the child is reaped.
pub fn spawn_engine(
    binary: &Path,
    args: &[String],
    env: &[(&str, &str)],
) -> io::Result<SpawnedEngine> {
    let mut child = spawn_child(binary, args, env, false)?;
    let pid = child.id();
    let (sender, events) = mpsc::channel();
    if let Some(stdout) = child.stdout.take() {
        read_lines(stdout, sender.clone(), EngineEvent::Stdout);
    }
    if let Some(stderr) = child.stderr.take() {
        read_lines(stderr, sender.clone(), EngineEvent::Stderr);
    }

    let child = Arc::new(Mutex::new(child));
    let waiter = Arc::clone(&child);
    std::thread::Builder::new()
        .name("aria2-exit-watcher".into())
        .spawn(move || loop {
            let status = {
                let mut child = waiter
                    .lock()
                    .unwrap_or_else(std::sync::PoisonError::into_inner);
                child.try_wait()
            };
            match status {
                Ok(Some(status)) => {
                    let (code, signal) = exit_parts(status);
                    let _ = sender.send(EngineEvent::Exited { code, signal });
                    return;
                }
                Ok(None) => std::thread::sleep(Duration::from_millis(50)),
                Err(_) => return,
            }
        })?;

    Ok(SpawnedEngine {
        process: EngineProcess { pid, child },
        events,
    })
}

fn read_lines(
    pipe: impl io::Read + Send + 'static,
    sender: mpsc::Sender<EngineEvent>,
    event: fn(Vec<u8>) -> EngineEvent,
) {
    std::thread::Builder::new()
        .name("aria2-log-reader".into())
        .spawn(move || {
            let mut reader = BufReader::new(pipe);
            let mut line = Vec::new();
            while matches!(reader.read_until(b'\n', &mut line), Ok(read) if read > 0) {
                let _ = sender.send(event(std::mem::take(&mut line)));
            }
        })
        .ok();
}

fn exit_parts(status: ExitStatus) -> (Option<i32>, Option<i32>) {
    #[cfg(unix)]
    {
        use std::os::unix::process::ExitStatusExt;
        (status.code(), status.signal())
    }
    #[cfg(not(unix))]
    {
        (status.code(), None)
    }
}

fn spawn_child(
    binary: &Path,
    args: &[String],
    env: &[(&str, &str)],
    quiet: bool,
) -> io::Result<Child> {
    let mut command = Command::new(binary);
    command
        .args(args)
        .envs(env.iter().copied())
        .stdin(Stdio::null());
    if quiet {
        command.stdout(Stdio::null()).stderr(Stdio::null());
    } else {
        command.stdout(Stdio::piped()).stderr(Stdio::piped());
    }
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        command.creation_flags(CREATE_NO_WINDOW);
    }
    bind_child_lifetime(&mut command);
    command.spawn().map_err(|error| {
        io::Error::new(
            error.kind(),
            format!(
                "failed to spawn aria2 binary '{}': {error}",
                binary.display()
            ),
        )
    })
}

fn parse_bundled_config() -> BTreeMap<String, String> {
    BUNDLED_CONFIG
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            (!line.is_empty() && !line.starts_with('#'))
                .then(|| line.split_once('='))
                .flatten()
        })
        .map(|(key, value)| (key.trim().to_string(), value.trim().to_string()))
        .collect()
}

fn path_value(path: &Path, option: &'static str) -> Result<String, Error> {
    match path.to_str() {
        Some(value) if !value.contains(['\r', '\n']) => Ok(value.to_string()),
        _ => Err(Error::InvalidPath(option)),
    }
}

fn validate_option(key: &str, value: &str) -> Result<(), Error> {
    let key_valid = !key.is_empty()
        && key
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-');
    if !key_valid || value.contains(['\r', '\n', '\0']) {
        return Err(Error::InvalidOption(key.to_string()));
    }
    Ok(())
}

fn ensure_file(path: &Path) -> io::Result<()> {
    match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
    {
        Ok(_) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::AlreadyExists => Ok(()),
        Err(error) => Err(error),
    }
}

#[cfg(any(target_os = "linux", target_os = "android"))]
fn bind_child_lifetime(command: &mut Command) {
    use std::os::unix::process::CommandExt;

    let parent = std::process::id() as libc::pid_t;
    // SAFETY: the closure only calls async-signal-safe libc functions between
    // fork and exec, which is what `pre_exec` requires.
    unsafe {
        command.pre_exec(move || {
            if libc::prctl(libc::PR_SET_PDEATHSIG, libc::SIGTERM) != 0 {
                return Err(io::Error::last_os_error());
            }
            // The parent may have died between fork and prctl.
            if libc::getppid() != parent {
                libc::_exit(1);
            }
            Ok(())
        });
    }
}

#[cfg(not(any(target_os = "linux", target_os = "android")))]
fn bind_child_lifetime(_command: &mut Command) {}

#[cfg(test)]
mod tests {
    use super::*;

    fn service() -> Aria2Service {
        Aria2Service::new(Aria2Config {
            binary: PathBuf::from("aria2-next"),
            data_dir: PathBuf::from("/data"),
            download_dir: PathBuf::from("/downloads"),
            rpc_port: DEFAULT_RPC_PORT,
            extra_options: BTreeMap::new(),
        })
    }

    fn option<'a>(content: &'a str, key: &str) -> Option<&'a str> {
        content.lines().find_map(|line| {
            let (candidate, value) = line.split_once('=')?;
            (candidate == key).then_some(value)
        })
    }

    #[test]
    fn config_keeps_bundled_defaults_and_adds_managed_options() {
        let content = service()
            .render_config(
                Path::new("/data/download.session"),
                Path::new("/data/state"),
            )
            .expect("render config");

        assert_eq!(option(&content, "state-save-interval"), Some("10"));
        assert_eq!(option(&content, "dir"), Some("/downloads"));
        assert_eq!(option(&content, "enable-rpc"), Some("true"));
        assert_eq!(option(&content, "rpc-listen-port"), Some("6800"));
        assert_eq!(option(&content, "rpc-listen-all"), Some("false"));
        assert_eq!(
            option(&content, "input-file"),
            Some("/data/download.session")
        );
        assert_eq!(option(&content, "state-dir"), Some("/data/state"));
        let expected_parent = std::process::id().to_string();
        assert_eq!(
            option(&content, "stop-with-process"),
            Some(expected_parent.as_str())
        );
    }

    #[test]
    fn config_rejects_paths_that_could_inject_options() {
        let service = Aria2Service::new(Aria2Config {
            binary: PathBuf::from("aria2-next"),
            data_dir: PathBuf::from("/data"),
            download_dir: PathBuf::from("/downloads\nenable-rpc=false"),
            rpc_port: DEFAULT_RPC_PORT,
            extra_options: BTreeMap::new(),
        });

        assert!(matches!(
            service.render_config(Path::new("/data/session"), Path::new("/data/state")),
            Err(Error::InvalidPath("dir"))
        ));
    }

    #[test]
    fn user_options_apply_but_managed_options_still_win() {
        let mut extra_options = BTreeMap::new();
        extra_options.insert("max-concurrent-downloads".into(), "12".into());
        extra_options.insert("rpc-listen-all".into(), "true".into());
        extra_options.insert("dir".into(), "/tmp/elsewhere".into());
        let service = Aria2Service::new(Aria2Config {
            binary: PathBuf::from("aria2-next"),
            data_dir: PathBuf::from("/data"),
            download_dir: PathBuf::from("/downloads"),
            rpc_port: DEFAULT_RPC_PORT,
            extra_options,
        });
        let content = service
            .render_config(Path::new("/data/session"), Path::new("/data/state"))
            .expect("render");
        assert_eq!(option(&content, "max-concurrent-downloads"), Some("12"));
        assert_eq!(option(&content, "dir"), Some("/downloads"));
        assert_eq!(option(&content, "rpc-listen-all"), Some("false"));
    }

    #[test]
    fn user_options_reject_config_injection() {
        let mut extra_options = BTreeMap::new();
        extra_options.insert("split".into(), "16\nenable-rpc=false".into());
        let service = Aria2Service::new(Aria2Config {
            binary: PathBuf::from("aria2-next"),
            data_dir: PathBuf::from("/data"),
            download_dir: PathBuf::from("/downloads"),
            rpc_port: DEFAULT_RPC_PORT,
            extra_options,
        });
        assert!(matches!(
            service.render_config(Path::new("/data/session"), Path::new("/data/state")),
            Err(Error::InvalidOption(_))
        ));
    }

    #[cfg(unix)]
    #[test]
    fn spawn_engine_streams_output_then_exit() {
        let spawned = spawn_engine(
            Path::new("/bin/sh"),
            &["-c".into(), "echo out; echo err >&2; exit 3".into()],
            &[],
        )
        .expect("spawn shell");
        let (_process, events) = spawned.into_parts();

        let mut stdout = String::new();
        let mut stderr = String::new();
        let mut exit = None;
        while exit.is_none() {
            match events.recv_timeout(Duration::from_secs(5)).expect("event") {
                EngineEvent::Stdout(line) => stdout.push_str(&String::from_utf8_lossy(&line)),
                EngineEvent::Stderr(line) => stderr.push_str(&String::from_utf8_lossy(&line)),
                EngineEvent::Exited { code, signal } => exit = Some((code, signal)),
            }
        }

        assert_eq!(stdout.trim(), "out");
        assert_eq!(stderr.trim(), "err");
        assert_eq!(exit, Some((Some(3), None)));
    }

    #[cfg(unix)]
    #[test]
    fn kill_terminates_the_supervised_process() {
        let spawned = spawn_engine(Path::new("/bin/sh"), &["-c".into(), "sleep 30".into()], &[])
            .expect("spawn shell");
        spawned.kill().expect("kill");
        let (_process, events) = spawned.into_parts();

        let mut exit = None;
        let deadline = Instant::now() + Duration::from_secs(5);
        while exit.is_none() && Instant::now() < deadline {
            if let Ok(EngineEvent::Exited { code, signal }) =
                events.recv_timeout(Duration::from_millis(500))
            {
                exit = Some((code, signal));
            }
        }
        assert!(exit.is_some(), "killed process never reported exit");
    }

    #[test]
    fn ensure_file_never_truncates_an_existing_session() {
        let directory =
            std::env::temp_dir().join(format!("rayload-aria2-service-{}", std::process::id()));
        std::fs::create_dir_all(&directory).unwrap();
        let session = directory.join("download.session");
        std::fs::write(&session, "existing").unwrap();

        ensure_file(&session).unwrap();

        assert_eq!(std::fs::read_to_string(&session).unwrap(), "existing");
        std::fs::remove_dir_all(directory).unwrap();
    }
}
