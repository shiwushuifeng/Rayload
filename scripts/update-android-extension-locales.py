KEYS = (
    "android-title",
    "android-description",
    "android-rpc-address",
    "android-rpc-secret-hint",
    "android-copy-rpc-secret",
    "android-rpc-secret-copied",
    "android-rpc-secret-empty",
)


def update_locale(locale: str, values: tuple[str, ...]) -> None:
    path = LOCALES_DIR / locale / "messages.json"
    messages = json.loads(path.read_text(encoding="utf-8"))
    extension = messages["extension"]
    extension.update(zip(KEYS, values, strict=True))
    path.write_text(json.dumps(messages, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


for locale, translations in sorted(TRANSLATIONS.items()):
    update_locale(locale, translations)
