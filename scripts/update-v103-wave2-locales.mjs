for (const locale of readdirSync(localesRoot)) {
  const directory = join(localesRoot, locale)
  if (!statSync(directory).isDirectory()) continue
  const path = join(directory, 'messages.json')
  const messages = JSON.parse(readFileSync(path, 'utf8'))
  for (const namespace of ['onboarding', 'preferences', 'task']) {
    messages[namespace] ??= {}
    Object.assign(messages[namespace], english[namespace], translations[locale]?.[namespace] ?? {})
  }
  for (const key of [
    'description',
    'storage-title',
    'notification-title',
    'battery-title',
    'appearance-description',
  ]) {
    delete messages.onboarding[key]
  }
  writeFileSync(path, `${JSON.stringify(messages, null, 2)}\n`)
}

