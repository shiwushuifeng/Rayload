def replace_product_name(value):
    if isinstance(value, str):
        return value.replace("Rayburst", "Rayload")
    if isinstance(value, list):
        return [replace_product_name(item) for item in value]
    if isinstance(value, dict):
        return {key: replace_product_name(item) for key, item in value.items()}
    return value


